def natureza_de(codigo):
    if codigo.startswith("2.3"):
        return "03"
    return {"1": "01", "2": "02", "3": "04", "4": "04"}.get(codigo[0], "09")


@transaction.atomic
def aplicar(cliente):
    """Copia o plano padrão para o cliente (só se ele ainda não tiver contas)."""
    from .models import Conta
    if cliente.contas.exists():
        raise ValueError("Este cliente já tem plano de contas.")
    for i, (codigo, nome, grupo, papel) in enumerate(PLANO, start=1):
        Conta.objects.create(cliente=cliente, codigo=codigo, reduzido=i, nome=nome, natureza=natureza_de(codigo),
                             sintetica=codigo.count(".") < 2 or len(codigo.split(".")) < 4,
                             grupo_dre=grupo, papel=papel)
    return len(PLANO)
